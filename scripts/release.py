"""Read the pinned SDK matrix and assemble one complete release."""

import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parent.parent
EMBEDDED_KEY = "embedded_public_key=''"
# The pinned usign format has an 8-byte fingerprint and a cached 32-byte
# public key. Skip the salt, checksum and private seed.
USIGN_SECRET = struct.Struct(">2s2sI24x8s32x32s")


def embed_public_key(directory, signing_key, usign):
    try:
        comment, encoded = signing_key.read_bytes().strip().splitlines()
        algorithm, kdf, rounds, fingerprint, public = USIGN_SECRET.unpack(
            base64.b64decode(encoded, validate=True)
        )
    except (ValueError, struct.error):
        raise ValueError("Malformed usign signing key") from None
    if not comment.startswith(b"untrusted comment: ") or (algorithm, kdf, rounds) != (b"Ed", b"BK", 0):
        raise ValueError("Expected an unencrypted Ed25519 key generated by usign")

    payload = base64.b64encode(algorithm + fingerprint + public).decode("ascii")
    template = (ROOT / "install.sh").read_text()
    if template.count(EMBEDDED_KEY) != 1:
        raise ValueError("Installer must contain exactly one empty embedded key")

    with tempfile.TemporaryDirectory() as temporary:
        verification_key = Path(temporary) / "release.pub"
        verification_key.write_text(f"untrusted comment: RouteGuard release key\n{payload}\n")
        verified = subprocess.run(
            [
                usign, "-q", "-V", "-p", str(verification_key),
                "-m", str(directory / "SHA256SUMS"), "-x", str(directory / "SHA256SUMS.sig"),
            ],
            check=False,
        )
        if verified.returncode:
            raise ValueError("The embedded public key did not verify the release manifest")

    (directory / "install.sh").write_text(
        template.replace(EMBEDDED_KEY, f"embedded_public_key='{payload}'", 1)
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("matrix")
    commands.add_parser("sdk").add_argument("architecture")
    bundle = commands.add_parser("bundle")
    bundle.add_argument("directory", type=Path)
    bundle.add_argument("--tag", default="")
    embed = commands.add_parser("embed-key")
    embed.add_argument("directory", type=Path)
    embed.add_argument("--signing-key", type=Path, required=True)
    embed.add_argument("--usign", default="usign")
    args = parser.parse_args()

    if args.command == "embed-key":
        try:
            embed_public_key(args.directory, args.signing_key, args.usign)
        except (ValueError, OSError) as exc:
            parser.error(str(exc))
        return

    manifest = json.loads((ROOT / "scripts/targets.json").read_text())
    targets = manifest["targets"]

    if args.command == "matrix":
        print(json.dumps({"architecture": [item["architecture"] for item in targets]}))
        return

    if args.command == "sdk":
        target = next((item for item in targets if item["architecture"] == args.architecture), None)
        if target is None:
            parser.error(f"Unsupported architecture: {args.architecture}")
        print(
            manifest["version"], target["target"], target["subtarget"],
            target["sdk"], target["sha256"],
            int(args.architecture == manifest["luci_architecture"]),
        )
        return

    expected = {f"routeguard-{item['architecture']}.apk" for item in targets}
    expected.add("luci-app-routeguard.apk")
    actual = {path.name for path in args.directory.glob("*.apk")}
    if actual != expected:
        parser.error(f"Incomplete release: missing {sorted(expected - actual)}, unexpected {sorted(actual - expected)}")

    if args.tag and not re.fullmatch(r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", args.tag):
        parser.error("Expected a release tag vMAJOR.MINOR.PATCH")

    checksums = [f"# RouteGuard {args.tag}\n"] if args.tag else []
    for name in sorted(expected):
        package = args.directory / name
        if package.stat().st_size == 0:
            parser.error(f"Empty package: {name}")
        checksums.append(f"{hashlib.sha256(package.read_bytes()).hexdigest()}  {name}\n")

    shutil.copy2(ROOT / "install.sh", args.directory / "install.sh")
    (args.directory / "SHA256SUMS").write_text("".join(checksums))


if __name__ == "__main__":
    main()
